export const topics = Object.keys(questionBank);
// Deterministic split: within each topic, every third group goes to training, the rest to test.
export function splitBank() {
  const train = [],
    test = [];
  for (const topic of topics)
    questionBank[topic].forEach((group, g) =>
      (g % 3 === 0 ? train : test).push(
        ...group.map(question => ({ question, topic, group: topic + g })),
      ),
    );
  return { train, test };
}
