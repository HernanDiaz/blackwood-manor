// The language of a phone or browser: the first of its preferences that the game speaks,
// and English for any other.
export function deviceLanguage(languages = []) {
  for (const l of languages) {
    if (/^es\b/i.test(l)) return 'es';
    if (/^en\b/i.test(l)) return 'en';
  }
  return 'en';
}
